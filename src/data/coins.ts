export const COINS: CoinInfo[] = PAIRS.map(([symbol, name]) => ({
  id: symbol,
  symbol,
  name,
}))

export const FOCUSED_SYMBOLS = ['BTC', 'ETH', 'SOL', 'BNB', 'XRP', 'ADA', 'DOGE', 'AVAX', 'DOT', 'LTC']

export const FOCUSED_COINS: CoinInfo[] = COINS.filter((coin) =>
  FOCUSED_SYMBOLS.includes(coin.symbol),
)

export const FOCUSED_COIN_IDS = FOCUSED_COINS.map((coin) => coin.id)

export const COIN_BY_ID: Record<string, CoinInfo> = Object.fromEntries(
  COINS.map((coin) => [coin.id, coin]),
)

/**
 * Curated portfolio universe: 20 high-liquidity Binance spot pairs with
 * verified live `@ticker` streams. The full catalog above contains
 * delisted/migrated pairs (BUSD, MATIC→POL, AGIX/OCEAN→FET, …) that never
 * emit ticker events, so the live portfolio, stream subscription, and
 * symbol pickers are all scoped to this set to guarantee complete data.
 */
export const PORTFOLIO_SYMBOLS = [
  'BTC',
  'ETH',
  'SOL',
  'BNB',
  'XRP',
  'DOGE',
  'ADA',
  'TRX',
  'AVAX',
  'LINK',
  'DOT',
  'LTC',
  'BCH',
  'NEAR',
  'ARB',
  'OP',
  'SUI',
  'ATOM',
  'ETC',
  'XLM',
]

export const PORTFOLIO_COINS: CoinInfo[] = PORTFOLIO_SYMBOLS.map((symbol) => {
  const coin = COIN_BY_ID[symbol]
  if (!coin) throw new Error(`Portfolio symbol missing from catalog: ${symbol}`)
  return coin
})

export const PORTFOLIO_COIN_IDS = PORTFOLIO_COINS.map((coin) => coin.id)